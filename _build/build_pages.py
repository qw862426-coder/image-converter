"""Build the feature landing pages (e.g. /heic-to-jpg/) from the tool pages plus pages_data.py.
Run from the repo root:  python3 _build/build_pages.py"""
import json, os, re, html, sys
sys.path.insert(0, os.path.dirname(__file__))
from pages_data import PAGES, NAMES

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = {'image': 'index.html', 'doc': 'document-to-pdf/index.html'}
SITE = 'https://picshifter.pages.dev'

def related(slug, lang):
    i = 0 if lang == 'en' else 1
    title = 'More free tools' if lang == 'en' else '다른 무료 도구'
    items = ''.join(f'<li><a href="/{k}/">{v[i]}</a></li>' for k, v in NAMES.items() if k != slug)
    return f'<h2>{title}</h2><ul class="related">{items}</ul>'

def build(p):
    src = open(os.path.join(ROOT, BASE[p['base']]), encoding='utf-8').read()
    en = p['meta']['en']
    def sub1(pattern, repl, s):
        out, n = re.subn(pattern, lambda m: repl, s, count=1, flags=re.S)
        assert n == 1, pattern
        return out
    s = sub1(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{SITE}/{p["slug"]}/">', src)
    s = sub1(r'<title>.*?</title>', f'<title>{html.escape(en["title"])}</title>', s)
    s = re.sub(r'(<meta(?=[^>]*id="metaDesc")[^>]*content=")[^"]*(")', lambda m: m.group(1) + html.escape(en['desc']) + m.group(2), s, count=1)
    s = sub1(r'<h1 data-i18n="h1">.*?</h1>', f'<h1 data-i18n="h1">{html.escape(en["h1"])}</h1>', s)
    s = sub1(r'<p data-i18n="sub">.*?</p>', f'<p data-i18n="sub">{html.escape(en["sub"])}</p>', s)
    preset = f'<script>window.PRESET={json.dumps(p["preset"])};window.PAGE_I18N={json.dumps(p["meta"], ensure_ascii=False)};</script>\n'
    s = sub1(r'<script src="/assets/codecs\.js"></script>', preset + '<script src="/assets/codecs.js"></script>', s)
    article = ('\n  <section class="doc landing">\n'
               f'    <article data-lang="en">\n{p["en"]}\n{related(p["slug"], "en")}\n    </article>\n'
               f'    <article data-lang="ko" hidden>\n{p["ko"]}\n{related(p["slug"], "ko")}\n    </article>\n'
               '  </section>\n')
    s = sub1(r'\n</main>', article + '</main>', s)
    s = s.replace('<link rel="stylesheet" href="/assets/base.css">', '<link rel="stylesheet" href="/assets/base.css">\n<!-- generated by _build/build_pages.py; edit pages_data.py instead -->', 1)
    out = os.path.join(ROOT, p['slug'], 'index.html')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8').write(s)
    return p['slug']

if __name__ == '__main__':
    print('built', [build(p) for p in PAGES])
